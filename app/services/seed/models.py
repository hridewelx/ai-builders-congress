"""Register the detector that is actually serving, so the UI cannot lie."""
from __future__ import annotations

import json

from ...core import db
from .. import detector
from .photos import _file_sha


def register_live_model() -> None:
    """Add the trained ONNX detector to the registry when it is present.

    The seeded history is generated by the baseline autoencoder; new uploads use
    this model. Both versions are recorded so the UI does not claim one model
    while running another.
    """
    if not detector.available():
        return
    if db.one("SELECT id FROM model_version WHERE name=?", (detector.MODEL_NAME,)):
        return
    ok, detail = detector.selftest()
    if not ok:
        return
    db.x("INSERT INTO model_version(name,artifact_sha,classes,eval_note,created_at) VALUES (?,?,?,?,?)",
         (detector.MODEL_NAME, _file_sha(detector.ONNX_PATH), json.dumps(list(detector.CLASSES)),
          "Supervised Faster R-CNN (MobileNetV3-FPN) on BDFD9 factory fabric (CC BY 4.0) plus staged "
          "panels. BDFD9 official test held out; see docs/MODEL_CARD.md. Proposes boxes only.", db.now()))
    db.x("INSERT INTO model_selftest(model_name,passed,detail,created_at) VALUES (?,?,?,?)",
         (detector.MODEL_NAME, 1, detail, db.now()))
    db.x("INSERT INTO model_activation(model_name,action,actor,reason,created_at) VALUES (?,?,?,?,?)",
         (detector.MODEL_NAME, "activate", "host-operator",
          "Trained ONNX detector present; new uploads use it. Seeded history remains on the baseline.",
          db.now()))
